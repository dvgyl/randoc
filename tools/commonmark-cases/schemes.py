#!/usr/bin/env python3
"""Writes crates/randoc-commonmark/src/schemes.rs, the URI schemes of `commonmark-extensions`.

The list comes from the value `schemes` in
src/Commonmark/Extensions/RebaseRelativePaths.hs of commonmark-extensions 0.2.7.3
(BSD-3-Clause). Give the path of that file.

Run: python3 tools/commonmark-cases/schemes.py PATH/RebaseRelativePaths.hs
"""

import re
import sys
from pathlib import Path


def main():
    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    start = source.index("schemes = Set.fromList")
    body = source[start:source.index("]", start)]
    names = sorted(set(re.findall(r'"([^"]+)"', body)))
    out = ["//! The URI schemes that `rebase_relative_paths` takes as absolute.",
           "//!",
           "//! Generated by `tools/commonmark-cases/schemes.py` from the value `schemes` of",
           "//! `Commonmark/Extensions/RebaseRelativePaths.hs` (`commonmark-extensions` 0.2.7.3,",
           "//! BSD-3-Clause). Do not edit.",
           "",
           "/// The schemes, in byte order.",
           "pub(crate) const SCHEMES: &[&str] = &["]
    out += [f'    "{name}",' for name in names]
    out += ["];", ""]
    path = Path(__file__).resolve().parents[2] / "crates/randoc-commonmark/src/schemes.rs"
    path.write_text("\n".join(out), encoding="utf-8")
    print(len(names), "schemes")


if __name__ == "__main__":
    main()
