#!/usr/bin/env python3
"""Generates the inventory of Pandoc features from the oracle binary.

The script runs `pandoc --list-*`, `pandoc --list-extensions=FORMAT` for each
format, and `pandoc --help`. It writes JSON files to `spec/inventory/` and the
Rust extension tables to `crates/randoc-core/src/extensions_data.rs`.

Usage: scripts/gen_inventory.py [--check]
The oracle path comes from the RANDOC_ORACLE_PANDOC environment variable.
With --check, the script writes nothing and fails if a file is out of date.
"""

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "spec" / "inventory"
RUST_OUT = ROOT / "crates" / "randoc-core" / "src" / "extensions_data.rs"


def oracle(*args):
    binary = os.environ.get("RANDOC_ORACLE_PANDOC")
    if not binary:
        sys.exit("gen_inventory: set RANDOC_ORACLE_PANDOC to the Pandoc 3.13 binary")
    result = subprocess.run([binary, *args], capture_output=True, text=True, check=True)
    return result.stdout


def lines(*args):
    return [line for line in oracle(*args).splitlines() if line.strip()]


def extension_lines(fmt):
    """Returns the `--list-extensions` lines, or an empty list when Pandoc rejects the format."""
    binary = os.environ["RANDOC_ORACLE_PANDOC"]
    result = subprocess.run([binary, f"--list-extensions={fmt}"], capture_output=True, text=True)
    if result.returncode != 0:
        return []
    return [line for line in result.stdout.splitlines() if line.strip()]


def parse_help(text):
    """Returns one record for each option line of `pandoc --help`."""
    options = []
    for line in text.splitlines():
        if not line.startswith("  "):
            continue
        short, long, argument, optional = [], [], None, False
        for token in re.split(r"[,\s]+", line.strip()):
            match = re.fullmatch(r"--([A-Za-z0-9-]+)(\[?=(.+?)\]?)?", token)
            if match:
                long.append(match.group(1))
                if match.group(3):
                    argument = match.group(3)
                    optional = token.endswith("]")
                continue
            match = re.fullmatch(r"-([A-Za-z0-9])", token)
            if match:
                short.append(match.group(1))
        if long:
            options.append(
                {"long": long, "short": short, "argument": argument, "optional_argument": optional}
            )
    return options


def camel(name):
    return "".join(part.capitalize() for part in name.split("_"))


def rust_tables(extensions, by_format):
    out = [
        "// Generated by scripts/gen_inventory.py from Pandoc 3.13. Do not edit.",
        "",
        "/// A syntax extension that a format can enable or disable.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
        "#[repr(u8)]",
        "pub enum Extension {",
    ]
    for name in extensions:
        out.append(f"    /// The `{name}` extension.")
        out.append(f"    {camel(name)},")
    out += [
        "}",
        "",
        "/// Each extension with its Pandoc name, in name order.",
        f"pub const ALL_EXTENSIONS: [(Extension, &str); {len(extensions)}] = [",
    ]
    for name in extensions:
        out.append(f'    (Extension::{camel(name)}, "{name}"),')
    out += [
        "];",
        "",
        "/// The extensions of one format.",
        "pub struct FormatExtensions {",
        "    /// The format name.",
        "    pub format: &'static str,",
        "    /// The extensions that are on by default.",
        "    pub default: &'static [Extension],",
        "    /// The extensions that the format accepts.",
        "    pub supported: &'static [Extension],",
        "}",
        "",
        "/// The extension sets of each format, in format name order.",
        f"pub const FORMAT_EXTENSIONS: [FormatExtensions; {len(by_format)}] = [",
    ]
    for fmt in sorted(by_format):
        data = by_format[fmt]
        default = ", ".join(f"Extension::{camel(n)}" for n in data["default"])
        supported = ", ".join(f"Extension::{camel(n)}" for n in data["supported"])
        out += [
            "    FormatExtensions {",
            f'        format: "{fmt}",',
            f"        default: &[{default}],",
            f"        supported: &[{supported}],",
            "    },",
        ]
    out += ["];", ""]
    return "\n".join(out)


def main():
    check = "--check" in sys.argv[1:]
    version = oracle("--version").splitlines()[0]
    input_formats = lines("--list-input-formats")
    output_formats = lines("--list-output-formats")

    by_format = {}
    names = set()
    for fmt in sorted(set(input_formats) | set(output_formats)):
        default, supported = [], []
        for line in extension_lines(fmt):
            sign, name = line[0], line[1:]
            supported.append(name)
            if sign == "+":
                default.append(name)
            names.add(name)
        by_format[fmt] = {"default": sorted(default), "supported": sorted(supported)}
    extensions = sorted(names)

    files = {
        INVENTORY / "oracle.json": {"version": version},
        INVENTORY / "input-formats.json": input_formats,
        INVENTORY / "output-formats.json": output_formats,
        INVENTORY / "extensions.json": {"extensions": extensions, "formats": by_format},
        INVENTORY / "highlight-languages.json": lines("--list-highlight-languages"),
        INVENTORY / "highlight-styles.json": lines("--list-highlight-styles"),
        INVENTORY / "options.json": parse_help(oracle("--help")),
    }
    rendered = {path: json.dumps(data, indent=1, ensure_ascii=False) + "\n" for path, data in files.items()}
    rendered[RUST_OUT] = rust_tables(extensions, by_format)

    stale = []
    for path, text in rendered.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if check and stale:
        sys.exit("gen_inventory: out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
    print(
        f"gen_inventory: {version}: {len(input_formats)} input formats, "
        f"{len(output_formats)} output formats, {len(extensions)} extensions, "
        f"{len(files[INVENTORY / 'options.json'])} options"
    )


if __name__ == "__main__":
    main()
