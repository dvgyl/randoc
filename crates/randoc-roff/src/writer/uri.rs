//! The URI check of the man writer: Pandoc writes a link or an image as a
//! `.UR` or `.MT` request only when its target is a URI with a known scheme.

/// Returns true when `url` has a known scheme and only URI characters.
pub(super) fn is_uri(url: &str) -> bool {
    let Some((scheme, rest)) = url.split_once(':') else {
        return false;
    };
    SCHEMES
        .binary_search(&scheme.to_ascii_lowercase().as_str())
        .is_ok()
        && uri_characters(rest)
}

fn uri_characters(text: &str) -> bool {
    let mut chars = text.chars();
    while let Some(c) = chars.next() {
        let valid = if c == '%' {
            chars.next().is_some_and(|h| h.is_ascii_hexdigit())
                && chars.next().is_some_and(|h| h.is_ascii_hexdigit())
        } else {
            c.is_ascii_alphanumeric()
                || "-._~!$&'()*+,;=:@/?#[]".contains(c)
                || !c.is_ascii() && !c.is_control() && !c.is_whitespace()
        };
        if !valid {
            return false;
        }
    }
    true
}

