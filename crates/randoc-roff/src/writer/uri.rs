#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schemes_are_sorted_and_checked() {
        assert!(SCHEMES.windows(2).all(|pair| pair[0] < pair[1]));
        for url in [
            "http://a.org",
            "HTTP://a.org",
            "mailto:a@b",
            "doi:10.1/x",
            "http:",
        ] {
            assert!(is_uri(url), "{url}");
        }
        for url in ["foo:bar", "c:/x.png", "a.png", "http:%zz", "http://a b"] {
            assert!(!is_uri(url), "{url}");
        }
    }
}
