pub(super) fn lookup(path: &str) -> Option<&'static str> {
    let mut parts = path.splitn(3, '.');
    let module = parts.next()?;
    let name = parts.next()?;
    let normalized;
    let key = if let Some(modifiers) = parts.next() {
        let mut modifiers: Vec<_> = modifiers.split('.').collect();
        modifiers.sort_unstable();
        normalized = format!("{module}.{name}.{}", modifiers.join("."));
        normalized.as_str()
    } else {
        path
    };
    let index = SYMBOLS.binary_search_by_key(&key, |&(name, _)| name).ok()?;
    Some(SYMBOLS[index].1)
}

