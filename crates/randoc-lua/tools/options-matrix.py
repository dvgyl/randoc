#!/usr/bin/env python3
"""Writes the oracle matrix of `PANDOC_READER_OPTIONS` and
`PANDOC_WRITER_OPTIONS`.

Usage (from the root of the worktree, after `. env.sh`):

    python3 -I crates/randoc-lua/tools/options-matrix.py

For each command line of `CASES` the script runs

    pandoc -f json -t FORMAT OPTIONS --lua-filter DUMP.lua

with Pandoc 3.13 (`$RANDOC_ORACLE_PANDOC`) on an empty document from the
standard input, in a temporary folder under `$TMPDIR/lua-s5`, and writes
the field lines that the filter writes to the file `$OPTIONS_DUMP` to
`crates/randoc-lua/tests/replay/options-expected.txt`. The filter shows
only the number of the abbreviations (a data file of Pandoc) and replaces
the working directory with `CWD`. At most one oracle process runs at a
time, with a limit of 60 s.
"""

import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, "..", "tests", "replay", "options-expected.txt")
FILTER = os.path.join(HERE, "..", "tests", "replay", "options-dump.lua")

CASES = [
    "-t json",
    "-t html --columns 50 --tab-stop 2",
    "-t markdown --toc --toc-depth 2 -N",
    "-t html --number-offset 2,3 --section-divs --id-prefix x- --email-obfuscation javascript",
    "-t html --mathjax",
    "-t html --katex",
    "-t latex --natbib --top-level-division chapter",
    "-t html --wrap none --dpi 120 --html-q-tags --ascii",
    "-t markdown --reference-links --reference-location block --markdown-headings setext --list-tables",
    "-t revealjs --slide-level 2 -i",
    "-t html -V foo=bar -V foo=baz -V k --variable n=1",
    "-t html --no-highlight",
    "-t html --lof --lot --link-images",
    "-t html --figure-caption-position above --table-caption-position below",
    "-t json --track-changes all --strip-comments --indented-code-classes a,b --default-image-extension png",
    "-t html --chunk-template x.html --reference-doc foo.docx",
    "-t html --biblatex",
    "-t html --wrap preserve --columns 100 --split-level 3",
    "-t latex --top-level-division part",
    "-t context --reference-location section",
    "-t gfm",
    "-t commonmark_x",
    "-t rst --email-obfuscation references",
    "-t org --track-changes reject",
    "-t docbook",
    "-t plain --columns 30",
]


def main():
    pandoc = os.environ.get("RANDOC_ORACLE_PANDOC")
    if not pandoc or "GHCRTS" not in os.environ:
        sys.exit("source env.sh first: RANDOC_ORACLE_PANDOC and GHCRTS must be set")
    parent = os.path.join(os.environ.get("TMPDIR", "/tmp"), "lua-s5")
    os.makedirs(parent, exist_ok=True)
    folder = tempfile.mkdtemp(prefix="options-", dir=parent)
    try:
        filter_path = os.path.join(folder, "dump.lua")
        shutil.copyfile(FILTER, filter_path)
        document = '{"pandoc-api-version":[1,23,1,2],"meta":{},"blocks":[]}'
        parts = [
            "# The oracle results of `tools/options-matrix.py`. Do not edit this file.\n"
        ]
        for case in CASES:
            command = [pandoc, "-f", "json", *case.split(), "--lua-filter", filter_path, "-o", "out"]
            dump = os.path.join(folder, "dump.txt")
            done = subprocess.run(command, cwd=folder, input=document.encode(), capture_output=True,
                                  timeout=60, env={**os.environ, "OPTIONS_DUMP": dump})
            if done.returncode != 0:
                sys.exit(f"{case}: exit {done.returncode}: {done.stderr.decode()}")
            with open(dump, encoding="utf-8") as handle:
                text = handle.read()
            parts.append(f"@@@ {case}\n{text}\n")
        with open(OUTPUT, "w", encoding="utf-8") as handle:
            handle.write("".join(parts))
        print(f"{len(CASES)} command lines")
    finally:
        shutil.rmtree(folder)


if __name__ == "__main__":
    main()
