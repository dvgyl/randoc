"""Write replay cases for one Lua module group."""

from pathlib import Path
from runpy import run_path

HERE = Path(__file__).resolve().parent
SHARED = run_path(str(HERE / "module-matrix.py"))
calls = SHARED["calls"]
lua_string = SHARED["lua_string"]

HELPER = SHARED["HELPER"] + r"""
local function keys(value)
  local names = {}
  for key in pairs(value) do names[#names + 1] = key end
  return table.concat(names, ',')
end
local function with_files(callback)
  return P.system.with_temporary_directory('lua-wave8b', callback)
end
local function write(path, data)
  local handle = assert(io.open(path, 'wb'))
  assert(handle:write(data))
  assert(handle:close())
end
"""


def write_matrix(module, groups, known=()):
    """Write the filters and their input documents in replay format."""
    output = ["# Generated by tools/" + module + "-matrix.py.\n"]
    for group, label in known:
        output.append(f"# known I-LUA-03 {module}-{group} {label}\n")
    for name, document in SHARED["DOCS"].items():
        output.append(f"@@@ doc {name}\n{document}\n")
    for name, (setup, probes) in groups.items():
        output.append(f"@@@ filter {module}-{name} empty small\n")
        output.append(HELPER)
        output.append("local function run(document)\n")
        output.append(setup + "\n")
        for label, code in probes:
            output.append(f"  probe({lua_string(label)}, function() {code} end)\n")
        output.append("end\n")
        output.append(SHARED["FOOTER"])
    path = HERE / ".." / "tests" / "replay" / (module + ".txt")
    path.write_text("".join(output), encoding="utf-8")
    print(f"{module}: {len(groups)} filters, {2 * len(groups)} runs, "
          f"{sum(len(probes) for _, probes in groups.values())} probes")
