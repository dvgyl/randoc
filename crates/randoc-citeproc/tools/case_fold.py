#!/usr/bin/env python3
"""Writes src/case_fold.rs: full Unicode case folding (`Data.Text.toCaseFold`,
which `CI Text` uses), from the Unicode Character Database of Python.

The table holds each character whose full case fold differs from its
lower case; each other character folds to its lower case.

Usage: python3 -I crates/randoc-citeproc/tools/case_fold.py OUTPUT_FILE
"""

import sys
import unicodedata


def rust_string(text):
    return "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{{{ord(c):X}}}" for c in text)


def main():
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if c.casefold() != c.lower():
            rows.append((cp, c.casefold()))
    lines = [
        "//! Full Unicode case folding, generated by `tools/case_fold.py` from the",
        f"//! Unicode Character Database {unicodedata.unidata_version}. Do not edit.",
        "",
        "/// The full case fold of a text, as `Data.Text.toCaseFold` gives it. Each",
        "/// character folds alone: a final sigma folds as each other sigma.",
        "pub fn fold(text: &str) -> String {",
        "    let mut out = String::with_capacity(text.len());",
        "    for c in text.chars() {",
        "        let index = FOLDS.binary_search_by_key(&u32::from(c), |&(code, _)| code);",
        "        match index.ok().and_then(|index| FOLDS.get(index)) {",
        "            Some((_, folded)) => out.push_str(folded),",
        "            None => out.extend(c.to_lowercase()),",
        "        }",
        "    }",
        "    out",
        "}",
        "",
        "/// The characters whose full case fold differs from their lower case.",
        f"const FOLDS: [(u32, &str); {len(rows)}] = [",
    ]
    lines += [f"    (0x{cp:04X}, \"{rust_string(f)}\")," for cp, f in rows]
    lines += ["];", ""]
    with open(sys.argv[1], "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


main()
