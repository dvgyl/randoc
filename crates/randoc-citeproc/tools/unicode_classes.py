#!/usr/bin/env python3
"""Writes src/unicode_class.rs: the Haskell character classes of the markup
parser and the name particles, from the Unicode Character Database of Python.

Haskell `isAlphaNum` selects the general categories L* and N*; `isLower`
selects the general category Ll. Rust `char::is_alphanumeric` and
`char::is_lowercase` use other properties.

Usage: python3 -I crates/randoc-citeproc/tools/unicode_classes.py OUTPUT_FILE
"""

import sys
import unicodedata


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        ok = test(unicodedata.category(chr(cp)))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, items):
    lines = [f"/// {doc}", f"const {name}: [(u32, u32); {len(items)}] = ["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in items]
    lines.append("];")
    return "\n".join(lines)


HEADER = f"""//! Haskell character classes, generated by `tools/unicode_classes.py` from
//! the Unicode Character Database {unicodedata.unidata_version}. Do not edit.

/// Haskell `isAlphaNum`: the general categories L* and N*.
pub fn is_alpha_num(c: char) -> bool {{
    if c.is_ascii() {{
        return c.is_ascii_alphanumeric();
    }}
    in_ranges(&ALPHA_NUM, c)
}}

/// Haskell `isLower`: the general category Ll.
pub fn is_lower(c: char) -> bool {{
    if c.is_ascii() {{
        return c.is_ascii_lowercase();
    }}
    in_ranges(&LOWER, c)
}}

fn in_ranges(ranges: &[(u32, u32)], c: char) -> bool {{
    let c = u32::from(c);
    let index = ranges.partition_point(|(_, last)| *last < c);
    ranges.get(index).is_some_and(|(first, _)| *first <= c)
}}
"""

TESTS = """
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn classes_follow_the_general_category() {
        assert!(is_alpha_num('a') && is_alpha_num('\\u{E9}') && is_alpha_num('\\u{B2}'));
        assert!(!is_alpha_num('\\u{93F}') && !is_alpha_num('\\u{345}') && !is_alpha_num('\\u{24B6}'));
        assert!(!is_alpha_num(' ') && !is_alpha_num('\\''));
        assert!(is_lower('a') && is_lower('\\u{DF}') && !is_lower('A'));
        assert!(!is_lower('\\u{AA}') && !is_lower('\\u{24D0}'));
        assert!(ALPHA_NUM.windows(2).all(|w| w[0].1 < w[1].0));
        assert!(LOWER.windows(2).all(|w| w[0].1 < w[1].0));
    }
}
"""


def main():
    alpha = ranges(lambda cat: cat[0] in "LN")
    lower = ranges(lambda cat: cat == "Ll")
    text = "\n".join([HEADER,
                      table("ALPHA_NUM", "The ranges of the categories L* and N*.", alpha), "",
                      table("LOWER", "The ranges of the category Ll.", lower), TESTS])
    with open(sys.argv[1], "w", encoding="utf-8") as out:
        out.write(text)


main()
