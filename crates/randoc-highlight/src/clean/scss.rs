pub(super) const fn merge_words<const N: usize>(
    common: &[&'static str],
    extra: &[&'static str],
) -> [&'static str; N] {
    assert!(N == common.len() + extra.len());
    let mut words = [""; N];
    let (mut i, mut j) = (0, 0);
    while i + j < N {
        if j == extra.len() || (i < common.len() && before(common[i], extra[j])) {
            words[i + j] = common[i];
            i += 1;
        } else {
            words[i + j] = extra[j];
            j += 1;
        }
    }
    words
}

const fn before(left: &str, right: &str) -> bool {
    let left = left.as_bytes();
    let right = right.as_bytes();
    let mut i = 0;
    while i < left.len() && i < right.len() {
        if left[i] != right[i] {
            return left[i] < right[i];
        }
        i += 1;
    }
    left.len() < right.len()
}
