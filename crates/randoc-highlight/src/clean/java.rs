//! Clean-room Java, from the Java Language Specification and black-box
//! runs of the oracle. Java gives the Javadoc tokens itself. The class
//! list holds the class names of the Java SE 6, 8 and 21 indexes that the
//! oracle highlights.

use super::{Ctx, Lang, M, Switch::*, opts};
use crate::syntax::Syntax;
use crate::token::TokenType::*;

/// The Javadoc block tags.
macro_rules! tags {
    () => {
        concat!(
            "(?:author|deprecated|exception|hidden|param|provides|return|see|serial",
            "|serialData|serialField|since|spec|throws|uses|version)"
        )
    };
}

pub(crate) fn syntax() -> Syntax {
    Lang::new("Java", "java", &["*.java"])
        .list("classes", CLASSES)
        .list("control flow", CONTROL_FLOW)
        .list("keywords", KEYWORDS)
        .list("types", TYPES)
        .context("Normal", Normal, |c| {
            c.rule(M::Re(r"/\*\*(?![*/])"), Comment, Push("Javadoc"))
                .rule(M::Str("/*"), Comment, Push("Block Comment"))
                .rule(M::Str("//"), Comment, Push("Line Comment"))
                .rule(M::Str("\"\"\""), String, Push("Text Block"))
                .rule(M::Char('"'), String, Push("String"))
                .rule(M::Re(CHAR), Char, Stay)
                .rule(M::Char('\''), Error, Stay)
                .rule(M::Re(r"package\b"), Keyword, Push("Import Path"))
                .rule(M::Re(r"import\b"), Keyword, Push("Import"))
                .rule(
                    M::Re(r"@(?:interface\b|[A-Za-z_$][\w$]*)?"),
                    Attribute,
                    Stay,
                )
                .rule(M::Re(BASE_N), BaseN, Stay)
                .rule(M::Re(FLOAT), Float, Stay)
                .rule(M::Re("[0-9][0-9_]*[lL]?"), DecVal, Stay)
                .rule(M::Re(r"non-sealed\b"), Keyword, Stay)
                .rule(M::Str("..."), Keyword, Stay)
                .rule(M::Kw("keywords"), Keyword, Stay)
                .rule(M::Kw("control flow"), ControlFlow, Stay)
                .rule(M::Kw("types"), DataType, Stay)
                .rule(M::Kw("classes"), BuiltIn, Stay)
                .rule(M::Re(r"[A-Za-z_$][\w$]*(?=\s*\()"), Function, Stay)
                .rule(M::Re(r"[A-Za-z_$][\w$]*"), Normal, Stay)
                .rule(M::Str("::"), Operator, Stay)
                .rule(M::Char('.'), Operator, Push("Member"))
                .rule(M::AnyOf("!%&()*+,-/:;<=>?[]^{|}~"), Operator, Stay)
        })
        // A name after `.` is a function, also a class name.
        .context("Member", Normal, |c| {
            c.rule(M::Re(r"[A-Za-z_$][\w$]*"), Function, Pop(1))
                .fallthrough(Pop(1))
        })
        .context("Import", Normal, |c| {
            c.rule(M::Spaces, Normal, Stay)
                .rule(M::Re(r"static\b"), Keyword, PopPush(1, "Import Path"))
                .fallthrough(PopPush(1, "Import Path"))
        })
        .context("Import Path", Import, |c| {
            c.rule(M::Char(';'), Operator, Pop(1))
                .rule(M::AnyOf(".*"), Operator, Stay)
                .line_end(Pop(1))
        })
        .context("Line Comment", Comment, |c| {
            c.rule(M::Spaces, Comment, Stay)
                .include("##Comments")
                .line_end(Pop(1))
        })
        .context("Block Comment", Comment, |c| {
            c.rule(M::Spaces, Comment, Stay)
                .rule(M::Str("*/"), Comment, Pop(1))
                .include("##Comments")
        })
        .context("String", String, |c| {
            c.rule(M::Re(ESCAPE), SpecialChar, Stay)
                .rule(M::Char('"'), String, Pop(1))
                .line_end(Pop(1))
        })
        .context("Text Block", String, |c| {
            c.rule(M::Re(ESCAPE), SpecialChar, Stay)
                .rule(M::Str("\"\"\""), String, Pop(1))
        })
        // Javadoc: names and white space are text, other characters are
        // comment. Before the first block tag, the white space before a
        // block tag is comment too.
        .context("Javadoc", Comment, |c| {
            javadoc(
                c.rule(
                    M::Re(concat!(r"[ \t]+(?=@", tags!(), r"\b)")),
                    Comment,
                    Stay,
                )
                .rule_with(
                    M::Re(concat!("@", tags!(), r"\b")),
                    Annotation,
                    PopPush(1, "Javadoc Block Tags"),
                    opts().lookahead(),
                ),
            )
        })
        .context("Javadoc Block Tags", Comment, javadoc)
        .context("Javadoc Line Start", Normal, |c| {
            c.rule(M::Spaces, Normal, Stay).fallthrough(Pop(1))
        })
        // The name after `@param`, with comment white space around it.
        .context("Javadoc Param", Comment, |c| {
            c.rule(M::Re(r"[ \t]+"), Comment, Stay)
                .rule(M::Re(r"\S+"), Annotation, PopPush(1, "Javadoc Param End"))
                .line_end(Pop(1))
        })
        .context("Javadoc Param End", Comment, |c| {
            c.rule(M::Re(r"[ \t]+"), Comment, Pop(1))
                .fallthrough(Pop(1))
                .line_end(Pop(1))
        })
        .context("Javadoc See", Normal, |c| {
            javadoc_markup(c.rule_with(M::Str("*/"), Comment, Pop(1), opts().lookahead()))
                .rule(M::Re(r"[^\w\s]"), Annotation, Stay)
                .line_end(Pop(1))
        })
        .context("Javadoc Link", Normal, |c| {
            c.rule_with(M::Str("*/"), Comment, Pop(1), opts().lookahead())
                .rule(M::Char('}'), Annotation, Pop(1))
                .rule(M::Re(r"[^\w\s]"), Annotation, Stay)
        })
        .context("Javadoc Tag Name", Keyword, |c| {
            c.rule(M::Re(r"[A-Za-z][\w-]*"), Keyword, PopPush(1, "Javadoc Tag"))
                .fallthrough(Pop(1))
        })
        .context("Javadoc Tag", Other, |c| {
            c.rule(M::Char('='), Operator, Stay)
                .rule(M::Re(r#""[^"]*"|'[^']*'"#), String, Stay)
                .rule(M::Re("/?>"), DataType, Pop(1))
                .rule_with(M::Str("*/"), Comment, Pop(1), opts().lookahead())
        })
        .build()
}

/// The Javadoc rules after the description rules.
fn javadoc(c: Ctx) -> Ctx {
    javadoc_markup(
        c.rule(M::Str("*/"), Comment, Pop(1))
            .rule_with(
                M::Re(r"\*(?!/)"),
                Comment,
                Push("Javadoc Line Start"),
                opts().first_non_space(),
            )
            .rule(
                M::Re(r"@(?:param|throws|exception)\b"),
                Annotation,
                Push("Javadoc Param"),
            )
            .rule(M::Re(r"@see\b"), Annotation, Push("Javadoc See"))
            .rule(M::Re(concat!("@", tags!(), r"\b")), Annotation, Stay)
            .rule(
                M::Re(r"\{@(?:link|linkplain|value)\b"),
                Annotation,
                Push("Javadoc Link"),
            )
            .rule(M::Re(r"\{@\w+[^}]*\}?"), Annotation, Stay),
    )
    .include("##Comments")
    .rule(M::Spaces, Normal, Stay)
    .rule(M::Re(r"[A-Za-z_]\w*"), Normal, Stay)
}

/// HTML tags and entities in Javadoc.
fn javadoc_markup(c: Ctx) -> Ctx {
    c.rule(M::Re("</?(?=[A-Za-z])"), DataType, Push("Javadoc Tag Name"))
        .rule(
            M::Re(r"&(?:#[0-9]+|#[xX][0-9A-Fa-f]+|[A-Za-z]\w*);"),
            DecVal,
            Stay,
        )
}

