//! Clean-room SQL, from the SQL standard, the MySQL and PostgreSQL
//! reference manuals and black-box runs of the oracle. One builder makes
//! `SQL`, `SQL (MySQL)` and `SQL (PostgreSQL)`. The start context of each
//! is `Normal`: `COBOL`, `SAS` and `Org Mode` include it. Keywords compare
//! without case. The word lists hold the words of the public references
//! that the oracle highlights with each attribute.

use super::{Ctx, Lang, M, Switch::*, opts};
use crate::syntax::Syntax;
use crate::token::TokenType::*;

/// The differences between the three languages.
#[derive(Clone, Copy, PartialEq)]
enum Dialect {
    Standard,
    MySql,
    PostgreSql,
}

/// The extensions of the SQL languages.
pub(super) const EXTENSIONS: &[&str] = &["*.sql", "*.ddl"];

pub(crate) fn sql() -> Syntax {
    family(super::SQL, Dialect::Standard)
}

pub(crate) fn mysql() -> Syntax {
    family(super::MYSQL, Dialect::MySql)
}

pub(crate) fn postgresql() -> Syntax {
    family(super::POSTGRESQL, Dialect::PostgreSql)
}

fn family(language: super::Language, dialect: Dialect) -> Syntax {
    let (keywords, control_flow, functions, types) = match dialect {
        Dialect::Standard => (SQL_KEYWORDS, SQL_CONTROL_FLOW, SQL_FUNCTIONS, SQL_TYPES),
        Dialect::MySql => (
            MYSQL_KEYWORDS,
            MYSQL_CONTROL_FLOW,
            MYSQL_FUNCTIONS,
            MYSQL_TYPES,
        ),
        Dialect::PostgreSql => (
            POSTGRESQL_KEYWORDS,
            POSTGRESQL_CONTROL_FLOW,
            POSTGRESQL_FUNCTIONS,
            POSTGRESQL_TYPES,
        ),
    };
    let lang = Lang::new(language)
        .list("keywords", keywords)
        .list("control flow", control_flow)
        .list("functions", functions)
        .list("types", types)
        .context("Normal", Normal, |c| normal(c, dialect))
        .context("Comment", Comment, |c| {
            c.rule(M::Spaces, Comment, Stay)
                .include("##Comments")
                .line_end(Pop(1))
        })
        .context("Block Comment", Comment, |c| {
            let c = if dialect == Dialect::PostgreSql {
                c.rule(M::Str("/*"), Comment, Push("Block Comment"))
            } else {
                c
            };
            c.rule(M::Spaces, Comment, Stay)
                .rule(M::Str("*/"), Comment, Pop(1))
                .include("##Comments")
        })
        // A line that starts with `@` runs a script in SQL*Plus.
        .context("Script", Other, |c| c.line_end(Pop(1)))
        // A name before `(`: a function of the list, or plain text.
        .context("Call", Normal, |c| {
            c.rule(M::KwI("functions"), Function, Pop(1))
                .rule(M::Re(r"[A-Za-z_][\w$]*"), Normal, Pop(1))
                .fallthrough(Pop(1))
        });
    let lang = match dialect {
        Dialect::Standard => lang
            .context("String", String, |c| {
                c.rule(M::Re(r#"\\[nrtbafv0\\"]"#), Char, Stay)
                    .rule(M::Str("''"), Char, Stay)
                    .rule(M::Char('\''), String, Pop(1))
            })
            .context("Identifier", Other, |c| {
                c.rule(M::Char('"'), Other, Pop(1))
                    .rule(M::Re(r#"\\[nrtbafv0\\"]"#), Char, Stay)
                    .line_end(Pop(1))
            }),
        Dialect::MySql => lang
            .context("String", String, |c| {
                c.rule(M::Re(r#"\\[nrtbafv0\\"']"#), Char, Stay)
                    .rule(M::Str("''"), String, Stay)
                    .rule(M::Char('\''), String, Pop(1))
            })
            .context("Double String", String, |c| {
                c.rule(M::Re(r#"\\[nrtbafv0\\"']"#), Char, Stay)
                    .rule(M::Str("\"\""), String, Stay)
                    .rule(M::Char('"'), String, Pop(1))
            })
            .context("Backtick String", String, |c| {
                c.rule(M::Char('`'), String, Pop(1))
            }),
        Dialect::PostgreSql => lang
            .context("String", VerbatimString, |c| {
                c.rule(M::Str("''"), Char, Stay)
                    .rule(M::Char('\''), String, Pop(1))
            })
            .context("Escape String", String, |c| {
                c.rule(M::Re(r"\\."), Char, Stay)
                    .rule(M::Str("''"), Char, Stay)
                    .rule(M::Char('\''), String, Pop(1))
            })
            .context("Identifier", Other, |c| {
                c.rule(M::Str("\"\""), Char, Stay)
                    .rule(M::Char('"'), Other, Pop(1))
            })
            // The body of a function: code between two equal tags.
            .context("Dollar Body Start", Normal, |c| {
                c.rule(M::Spaces, Normal, Stay)
                    .rule(
                        M::Re(r"\$([A-Za-z_]\w*|)\$"),
                        Function,
                        PopPush(1, "Dollar Body"),
                    )
                    .fallthrough(Pop(1))
            })
            .context("Dollar Body", Normal, |c| {
                c.dynamic()
                    .rule_with(M::Re(r"\$%1\$"), Function, Pop(1), opts().dynamic())
                    .include("Normal")
            })
            // `$tag$ ... $tag$`: the end tag is the start tag.
            .context("Dollar String", VerbatimString, |c| {
                c.dynamic()
                    .rule_with(M::Re(r"\$%1\$"), Operator, Pop(1), opts().dynamic())
            }),
    };
    lang.build()
}

/// The rules of the start context.
fn normal(c: Ctx, dialect: Dialect) -> Ctx {
    let c = c
        .rule(M::Re("^@.*"), Other, Stay)
        .rule(M::Str("--"), Comment, Push("Comment"))
        .rule(M::Str("/*"), Comment, Push("Block Comment"));
    let c = match dialect {
        Dialect::Standard => c
            .rule(M::Char('\''), String, Push("String"))
            .rule(M::Char('"'), Other, Push("Identifier"))
            .rule(M::Re("0[xX][0-9A-Fa-f]+"), BaseN, Stay),
        Dialect::MySql => c
            .rule(M::Char('#'), Comment, Push("Comment"))
            .rule(M::Char('\''), String, Push("String"))
            .rule(M::Char('"'), String, Push("Double String"))
            .rule(M::Char('`'), String, Push("Backtick String"))
            .rule(M::Re("0[xX][0-9A-Fa-f]+"), BaseN, Stay),
        Dialect::PostgreSql => c
            .rule(M::Re("[Ee]'"), String, Push("Escape String"))
            .rule(M::Char('\''), VerbatimString, Push("String"))
            .rule(M::Char('"'), Other, Push("Identifier"))
            .rule_with(
                M::Re(r"CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\b"),
                Keyword,
                Stay,
                opts().insensitive(),
            )
            .rule_with(
                M::Re(r"DO\s+\$([A-Za-z_]\w*|)\$"),
                Keyword,
                Push("Dollar Body"),
                opts().insensitive(),
            )
            .rule_with(
                M::Re(r"AS\b(?=\s+\$(?:[A-Za-z_]\w*)?\$)"),
                Keyword,
                Push("Dollar Body Start"),
                opts().insensitive(),
            )
            .rule(M::Re(r"\$([^$\n]*)\$"), Operator, Push("Dollar String"))
            .rule(M::Re(r"\$[0-9]+"), Normal, Stay),
    };
    let c = c
        .rule(
            M::Re(r"[0-9]*\.[0-9]+(?:[eE][-+]?[0-9]+)?|[0-9]+\.[0-9]*(?:[eE][-+]?[0-9]+)?"),
            Float,
            Stay,
        )
        .rule(M::Re("[0-9]+"), DecVal, Stay)
        .rule(M::KwI("keywords"), Keyword, Stay)
        .rule(M::KwI("control flow"), ControlFlow, Stay)
        .rule(M::KwI("types"), DataType, Stay);
    let c = if dialect == Dialect::PostgreSql {
        c.rule_with(
            M::Re(r"[A-Za-z_][\w$]*\s*\("),
            Normal,
            Push("Call"),
            opts().lookahead(),
        )
    } else {
        c.rule(M::KwI("functions"), Function, Stay)
    };
    let c = c.rule(M::Re(r"[A-Za-z_][\w$]*"), Normal, Stay);
    match dialect {
        Dialect::Standard => {
            c.rule(M::Re(r":\w+"), Char, Stay)
                .rule(M::Re(r"\|\||[-+*/<>=!]+"), Operator, Stay)
        }
        Dialect::MySql => {
            c.rule(M::AnyOf(".&:"), Char, Stay)
                .rule(M::Re(r"\|\||[-+*/<>=!]+"), Operator, Stay)
        }
        Dialect::PostgreSql => {
            c.rule(M::AnyOf("&:"), Char, Stay)
                .rule(M::Re(r"[-+*/<>=!%^|~#@]+"), Operator, Stay)
        }
    }
}

