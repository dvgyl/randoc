#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_names_win_in_class_order() {
        assert!(NAMES.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(EXTENSIONS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        let classes = |items: &[&str]| {
            items
                .iter()
                .map(|&item| item.to_owned())
                .collect::<Vec<_>>()
        };
        assert_eq!(tei_language(&classes(&["numberLines", "python"])), "python");
        assert_eq!(tei_language(&classes(&["Python"])), "Python");
        assert_eq!(tei_language(&classes(&["py", "rust"])), "python");
        assert_eq!(tei_language(&classes(&["cpp"])), "c++");
        assert_eq!(tei_language(&classes(&["foo"])), "");
        assert_eq!(tei_language(&[]), "");
    }
}
