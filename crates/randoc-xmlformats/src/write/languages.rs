//! The language of a TEI code block, as Pandoc 3.13 chooses it.
//!
//! Each class gives a language: a highlighting language name stays as
//! written, and a file extension gives the lower-case name of its language.
//! The first language wins, and a block without one has an empty language.
//! For example, `{.numberLines .py}` gives `python`.
//!
//! The tables come from oracle probes: one TEI code block for each language
//! of `pandoc --list-highlight-languages`, each file extension of the
//! `randoc-highlight` definitions and common extensions, in lower case and
//! with a capital first letter. An extension outside these probes has no
//! language here.

/// Returns the TEI language of the first class that has one.
pub(super) fn tei_language(classes: &[String]) -> &str {
    classes
        .iter()
        .find_map(|class| {
            let lower = class.to_ascii_lowercase();
            if NAMES.binary_search(&lower.as_str()).is_ok() {
                return Some(class.as_str());
            }
            EXTENSIONS
                .binary_search_by(|(extension, _)| extension.cmp(&lower.as_str()))
                .ok()
                .map(|index| EXTENSIONS[index].1)
        })
        .unwrap_or("")
}

