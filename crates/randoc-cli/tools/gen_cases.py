"""Writes the generated case files of the cli suite.

Usage: python3 crates/randoc-cli/tools/gen_cases.py WORKTREE_ROOT
Then run `randoc-harness record --filter cli/` for the oracle results.
"""
import json, sys

def defaults_types(root):
    keys = """from reader to writer output-file input-file input-files data-dir metadata metadata-file metadata-files
    file-scope sandbox standalone template variables wrap ascii toc table-of-contents toc-depth lof list-of-figures lot
    list-of-tables number-sections number-offset top-level-division extract-media resource-path include-in-header
    include-before-body include-after-body syntax-highlighting highlight-style syntax-definition syntax-definitions dpi eol
    columns preserve-tabs tab-stop pdf-engine pdf-engine-opt pdf-engine-opts reference-doc self-contained embed-resources
    link-images request-headers no-check-certificate abbreviations indented-code-classes default-image-extension filters
    shift-heading-level-by track-changes strip-comments reference-links reference-location figure-caption-position
    table-caption-position markdown-headings list-tables listings incremental slide-level section-divs html-q-tags
    email-obfuscation identifier-prefix title-prefix css epub-subdirectory epub-cover-image epub-title-page epub-metadata
    epub-fonts split-level epub-chapter-level chunk-template ipynb-output cite-method bibliography csl
    citation-abbreviations html-math-method trace dump-args ignore-args verbosity fail-if-warnings log-file citeproc
    defaults""".split()
    kinds = [("string", "x", '"x"'), ("number", "3", "3"), ("bool", "true", "true"), ("null", "~", "null"),
             ("list", "[a, b]", '["a","b"]'), ("map", "{a: b}", '{"a":"b"}')]
    doc = '{"pandoc-api-version":[1,23,1,2],"meta":{},"blocks":[]}'
    out = ["# Each defaults key with each kind of value, in YAML and JSON form. Generated by crates/randoc-cli/tools/gen_cases.py.\n"]
    for key in keys:
        for kind, yaml_value, json_value in kinds:
            for form in ("yaml", "json"):
                text = f"{key}: {yaml_value}\n" if form == "yaml" else "{" + json.dumps(key) + ":" + json_value + "}\n"
                out.append(f'\n[[case]]\nid = "{key}-{kind}-{form}"\ncmd = ["-d", "d.yaml", "-f", "json", "-t", "json", "a.json"]\n'
                           f'files = {{ "d.yaml" = {json.dumps(text)}, "a.json" = {json.dumps(doc)} }}\n')
    open(f"{root}/conformance/cases/cli/defaults-types.toml", "w").write("".join(out))
    print(len(keys) * len(kinds) * 2)


def clusters(root):
    # -F and -L are left out: they start a system program (I-CLI-02).
    shorts = "frtwoMdsVNHBApiTcCDh"
    booleans = "sNpi"
    doc = '{"pandoc-api-version":[1,23,1,2],"meta":{},"blocks":[]}'
    clusters = [x + y + suffix for x in shorts for y in shorts for suffix in ("", "false")]
    clusters += [x + y + z + suffix for x in "sN" for y in "sN" for z in shorts for suffix in ("true", "x")]
    out = ["# Short-option clusters. Generated by crates/randoc-cli/tools/gen_cases.py.\n"]
    for cluster in clusters:
        ident = "cluster-" + "".join(c if c.islower() else c.lower() + "_" for c in cluster)
        out.append(f'\n[[case]]\nid = "{ident}"\ncmd = ["-f", "json", "-t", "json", "-{cluster}"]\ninput = {json.dumps(doc)}\n')
    ids = [o.split('"')[1] for o in out[1:]]
    assert len(ids) == len(set(ids))
    open(f"{root}/conformance/cases/cli/clusters.toml", "w").write("".join(out))
    print(len(clusters))


DOC = '{"pandoc-api-version":[1,23,1,2],"meta":{},"blocks":[]}'
HDOC = '{"pandoc-api-version":[1,23,1,2],"meta":{},"blocks":[{"t":"Header","c":[2,["",[],[]],[]]}]}'


def write_cases(root, name, title, cases):
    """Writes one case file. Each case is (id, cmd, input or None, files)."""
    out = [f"# {title} Generated by crates/randoc-cli/tools/gen_cases.py.\n"]
    ids = set()
    for ident, cmd, stdin, files in cases:
        assert ident not in ids, ident
        ids.add(ident)
        text = f'\n[[case]]\nid = "{ident}"\ncmd = {json.dumps(cmd)}\n'
        if stdin is not None:
            text += f"input = {json.dumps(stdin)}\n"
        if files:
            text += "files = { " + ", ".join(f"{json.dumps(k)} = {json.dumps(v)}" for k, v in files.items()) + " }\n"
        out.append(text)
    open(f"{root}/conformance/cases/cli/{name}.toml", "w").write("".join(out))
    return len(cases)


def paths(root):
    """Each path key of a defaults file with each form of path."""
    contents = {
        "abbreviations": "Mr.\n", "metadata-file": "m: 1\n", "input-file": DOC,
        "include-in-header": "x\n", "template": "T\n", "defaults": "to: json\n",
        "output-file": None, "log-file": None,
    }
    forms = [
        ("dot", "${.}/F"), ("dot-dot-part", "${.}/./F"), ("dot-double-slash", "${.}//F"),
        ("dot-parent", "${.}/../sub/F"), ("home", "${HOME}/F"), ("userdata", "${USERDATA}/F"),
        ("undefined-variable", "${NOSUCHVAR}F"), ("relative", "F"), ("relative-dot", "./F"),
        ("relative-parent", "sub/../F"), ("relative-double-slash", "sub//F"),
        ("missing", "nosuch.txt"), ("missing-dot-part", "sub/./nosuch.txt"),
        ("missing-parent", "sub/../nosuch.txt"),
    ]
    cases = []
    for key, content in contents.items():
        for form, value in forms:
            # A write into the home folder names the work folder, which changes on each run.
            if content is None and form in ("home", "userdata"):
                continue
            files = {"sub/d.yaml": f"from: json\nto: json\n{key}: {value}\n"}
            if content is not None:
                for where in ("F", "sub/F", ".home/F", ".home/.local/share/pandoc/F"):
                    files[where] = content
            cmd = ["-d", "sub/d.yaml"]
            if key != "input-file":
                cmd.append("a.json")
                files["a.json"] = DOC
            cases.append((f"{key}-{form}", cmd, None, files))
    return [("path-" + c[0],) + c[1:] for c in cases]


def duplicates(root):
    """Duplicate keys in YAML and JSON defaults files at each level."""
    rows = [
        ("top", '{"from":"json","to":"json","to":"native"}', "from: json\nto: json\nto: native\n"),
        ("top-reverse", '{"from":"json","to":"native","to":"json"}', "from: json\nto: native\nto: json\n"),
        ("top-bad-first", '{"from":"bad","from":"json","to":"json"}', "from: bad\nfrom: json\nto: json\n"),
        ("metadata-key", '{"from":"json","to":"json","metadata":{"a":1,"a":2}}', "from: json\nto: json\nmetadata:\n  a: 1\n  a: 2\n"),
        ("metadata-twice", '{"from":"json","to":"json","metadata":{"a":1},"metadata":{"b":2}}', "from: json\nto: json\nmetadata: {a: 1}\nmetadata: {b: 2}\n"),
        ("variables-key", '{"from":"json","to":"json","variables":{"a":1,"a":2}}', "from: json\nto: json\nvariables:\n  a: 1\n  a: 2\n"),
        ("filter-map-key", '{"from":"json","to":"json","filters":[{"type":"json","type":"lua","path":"x"}]}', "from: json\nto: json\nfilters:\n- type: json\n  type: lua\n  path: x\n"),
        ("math-map-key", '{"from":"json","to":"json","html-math-method":{"method":"plain","method":"x"}}', "from: json\nto: json\nhtml-math-method: {method: plain, method: x}\n"),
        ("bool-then-bad", '{"from":"json","to":"json","toc":true,"toc":"x"}', "from: json\nto: json\ntoc: true\ntoc: x\n"),
        ("int", '{"from":"json","to":"json","shift-heading-level-by":1,"shift-heading-level-by":-1}', "from: json\nto: json\nshift-heading-level-by: 1\nshift-heading-level-by: -1\n"),
        ("defaults", '{"from":"json","to":"json","defaults":"nosuchd","defaults":"e.yaml"}', "from: json\nto: json\ndefaults: nosuchd\ndefaults: e.yaml\n"),
        ("unknown-sorted", '{"foo":1,"bar":2}', "foo: 1\nbar: 2\n"),
    ]
    cases = []
    for name, json_text, yaml_text in rows:
        for form, text in (("json", json_text), ("yaml", yaml_text)):
            files = {"d.cfg": text, "a.json": HDOC, "e.yaml": "to: json\n"}
            cases.append((f"{name}-{form}", ["-d", "d.cfg", "a.json"], None, files))
    return [("duplicate-" + c[0],) + c[1:] for c in cases]


def combinations(root):
    """Two defaults files with the same key, and a key with the command line, in both orders."""
    rows = [
        ("to", "to: native", "to: json", ["-t", "native"]),
        ("shift", "shift-heading-level-by: 1", "shift-heading-level-by: -1", ["--shift-heading-level-by=2"]),
        ("standalone", "standalone: true", "standalone: false", ["-s"]),
        ("eol", "eol: crlf", "eol: lf", ["--eol=crlf"]),
        ("metadata", "metadata: {a: 1}", "metadata: {a: 2}", ["-M", "a=3"]),
        ("metadata-files", "metadata-files: [m1.yaml]", "metadata-files: [m2.yaml]", ["--metadata-file=m1.yaml"]),
        ("include", "include-in-header: [i1.txt]", "include-in-header: [nosuch.txt]", ["-H", "i1.txt"]),
        ("template", "template: t1.json", "template: nosuch.json", ["--template=t1.json"]),
        ("toc-depth", "toc-depth: 2", "toc-depth: x", ["--toc-depth=3"]),
        ("from", "from: native", "from: ~", ["-f", "native"]),
        ("verbosity", "verbosity: INFO", "verbosity: ERROR", ["--quiet"]),
        ("tab-stop", "tab-stop: 8", "tab-stop: 2", ["--tab-stop=4"]),
        ("syntax-highlighting", "syntax-highlighting: nosuchstyle", "syntax-highlighting: pygments", ["--syntax-highlighting=kate"]),
        ("output", "output-file: o1.json", "output-file: ~", ["-o", "o2.json"]),
    ]
    files_all = {"m1.yaml": "x: 1\n", "m2.yaml": "y: 2\n", "i1.txt": "x\n", "t1.json": "T\n", "a.json": HDOC.replace("[]]}]}", "[{\"t\":\"Str\",\"c\":\"a\\tb\"}]]}]}")}
    cases = []
    for name, first, second, cli in rows:
        files = dict(files_all, **{"p.yaml": "from: json\nto: json\n" + first + "\n", "q.yaml": second + "\n"})
        cases.append((f"{name}-two-files", ["-d", "p.yaml", "-d", "q.yaml", "a.json"], None, files))
        cases.append((f"{name}-two-files-reverse", ["-d", "q.yaml", "-d", "p.yaml", "a.json"], None, files))
        cases.append((f"{name}-cli-first", cli + ["-d", "p.yaml", "a.json"], None, files))
        cases.append((f"{name}-cli-last", ["-d", "p.yaml"] + cli + ["a.json"], None, files))
    return [("combination-" + c[0],) + c[1:] for c in cases]


def sandbox(root):
    """Each file-reading option with --sandbox and each kind of path."""
    theme = '{"text-styles":{}}'
    options = [
        ("input", lambda p: [p], DOC), ("metadata-file", lambda p: ["--metadata-file=" + p, "a.json"], "m: 1\n"),
        ("include-in-header", lambda p: ["-H", p, "a.json"], "x\n"), ("abbreviations", lambda p: ["--abbreviations=" + p, "a.json"], "Mr.\n"),
        ("template", lambda p: ["--template=" + p, "a.json"], "T\n"), ("theme", lambda p: ["--syntax-highlighting=" + p, "a.json"], theme),
        ("defaults", lambda p: ["-d", p, "a.json"], "to: json\n"), ("epub-metadata", lambda p: ["--epub-metadata=" + p, "a.json"], "<x/>\n"),
        ("css", lambda p: ["--css=" + p, "a.json"], "x\n"), ("bibliography", lambda p: ["--bibliography=" + p, "a.json"], "[]\n"),
        ("reference-doc", lambda p: ["--reference-doc=" + p, "a.json"], "x\n"),
    ]
    kinds = [("file", "f.theme"), ("file-no-extension", "fnoext"), ("missing", "nosuch.theme"), ("directory", "dir"),
             ("dev-null", "/dev/null"), ("dev-stdin", "/dev/stdin")]
    cases = []
    for name, cmd_of, content in options:
        for kind, path in kinds:
            files = {"a.json": DOC, "dir/x": "x"}
            if kind.startswith("file"):
                files[path] = content
            stdin = content if kind == "dev-stdin" else ""
            cases.append((f"{name}-{kind}", ["--sandbox", "-f", "json", "-t", "json"] + cmd_of(path), stdin, files))
    return cases


def includes(root):
    """Each include option and key with each path form, with and without --resource-path."""
    forms = [("absolute-missing", "/nosuch/x.txt"), ("absolute-existing", "/dev/null"), ("relative", "x.txt"),
             ("relative-dot", "./x.txt"), ("relative-in-sub", "y.txt"), ("relative-missing", "nosuch.txt"),
             ("directory", "dir"), ("expanded-existing", "${.}/x.txt")]
    files = {"x.txt": "x\n", "sub/y.txt": "y\n", "sub/x.txt": "sx\n", "dir/z": "z", "a.json": DOC}
    cases = []
    for short, key in (("-H", "include-in-header"), ("-B", "include-before-body"), ("-A", "include-after-body")):
        for form, path in forms:
            for extra_name, extra in (("", []), ("-resource-path", ["--resource-path=sub"]), ("-two-paths", ["--resource-path=.:sub"])):
                if not form.startswith("expanded"):
                    cases.append((f"{key}-option-{form}{extra_name}", ["-f", "json", "-t", "json"] + extra + [short, path, "a.json"], None, files))
                cases.append((f"{key}-key-{form}{extra_name}", ["-f", "json", "-t", "json"] + extra + ["-d", "d.yaml", "a.json"], None,
                              dict(files, **{"d.yaml": f"{key}: {path}\n"})))
    return cases


def standalone(root):
    """-s, and each option or defaults key that can turn on standalone output, for each format of the branch."""
    native_doc = '[ Para [ Str "a" ] ]\n'
    cases = []
    for writer in ("json", "native"):
        for reader, doc in (("json", DOC), ("native", native_doc)):
            for name, extra in (("plain", []), ("standalone", ["-s"]), ("standalone-crlf", ["-s", "--eol=crlf"]),
                                ("standalone-false", ["--standalone=false"]), ("crlf", ["--eol=crlf"])):
                cases.append((f"{reader}-to-{writer}-{name}", ["-f", reader, "-t", writer] + extra, doc, {}))
    files = {"t.txt": "T\n", "i.txt": "x\n", "e.xml": "<x/>\n", "c.png": "x", "r.docx": "x", "c.css": "x", "ab.txt": "Mr.\n"}
    options = [("template", ["--template=t.txt"]), ("include-in-header", ["-H", "i.txt"]), ("include-before-body", ["-B", "i.txt"]),
               ("include-after-body", ["-A", "i.txt"]), ("title-prefix", ["-T", "x"]), ("css", ["-c", "c.css"]), ("toc", ["--toc"]),
               ("number-sections", ["-N"]), ("self-contained", ["--self-contained"]), ("embed-resources", ["--embed-resources"]),
               ("epub-metadata", ["--epub-metadata=e.xml"]), ("epub-cover-image", ["--epub-cover-image=c.png"]),
               ("reference-doc", ["--reference-doc=r.docx"]), ("abbreviations", ["--abbreviations=ab.txt"]),
               ("variable", ["-V", "a=b"]), ("metadata", ["-M", "a=b"]), ("highlight", ["--syntax-highlighting=kate"])]
    for name, extra in options:
        for writer in ("json", "native"):
            cases.append((f"option-{name}-{writer}", ["-f", "json", "-t", writer] + extra, DOC, files))
    keys = [("template", "t.txt"), ("include-in-header", "i.txt"), ("include-before-body", "i.txt"), ("include-after-body", "i.txt"),
            ("title-prefix", "x"), ("css", "c.css"), ("toc", "true"), ("number-sections", "true"), ("self-contained", "true"),
            ("embed-resources", "true"), ("epub-metadata", "e.xml"), ("epub-cover-image", "c.png"), ("reference-doc", "r.docx"),
            ("abbreviations", "ab.txt"), ("variables", "{a: b}"), ("standalone", "true"), ("standalone-false", "false")]
    for key, value in keys:
        real = "standalone" if key == "standalone-false" else key
        for writer in ("json", "native"):
            files_key = dict(files, **{"d.yaml": f"from: json\nto: {writer}\n{real}: {value}\n"})
            cases.append((f"key-{key}-{writer}", ["-d", "d.yaml"], DOC, files_key))
            cases.append((f"key-{key}-{writer}-then-no-standalone", ["-d", "d.yaml", "--standalone=false"], DOC, files_key))
    return write_cases(root, "standalone", "Standalone output for each format, option and defaults key.", cases)


if __name__ == "__main__":
    root = sys.argv[1]
    defaults_types(root)
    clusters(root)
    parts = [paths(root), duplicates(root), combinations(root)]
    count = write_cases(root, "defaults-matrix",
                        "Path forms, duplicate keys and repeated keys of defaults files.", [c for part in parts for c in part])
    files = write_cases(root, "sandbox", "Each file-reading option with --sandbox and each kind of path, and each include option and key with each path form.",
                        sandbox(root) + [("include-" + c[0],) + c[1:] for c in includes(root)])
    print({"defaults-matrix": count, "sandbox-and-includes": files, "standalone": standalone(root)})
